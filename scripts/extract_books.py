def run_batch(batch_name: str):
    if batch_name not in BATCHES:
        raise SystemExit(f"Unknown batch {batch_name!r} — choose one of {list(BATCHES)}")
    cfg = BATCHES[batch_name]

    api_key = os.environ["GEMINI_API_KEY"]
    client = genai.Client(api_key=api_key)

    with open(CANONICAL_PATH, encoding="utf-8") as f:
        canonical_chars = json.load(f)
    with open(cfg["text_path"], encoding="utf-8") as f:
        book_text = f.read()

    prompt = build_prompt(
        canonical_chars, book_text, cfg["book_label"],
        cfg["location_floor"], cfg["event_floor"], cfg["order_note"],
        cfg.get("extra_notes", ""),
    )

    print(f"Calling {MODEL} for batch {batch_name!r} ({len(prompt)} chars prompt)...")
    response = client.models.generate_content(
        model=MODEL,
        contents=prompt,
        config=types.GenerateContentConfig(
            response_mime_type="application/json",
            response_schema=ExtractionResult,
        ),
    )

    result: ExtractionResult = response.parsed
    result_dict = _to_traditional(result.model_dump())

    with open(cfg["output_path"], "w", encoding="utf-8") as f:
        json.dump(result_dict, f, ensure_ascii=False, indent=2)

    print(f"Wrote {len(result.locations)} locations, {len(result.events)} events, "
          f"{len(result.relationships)} relationships to {cfg['output_path']}")
    if result.unmatched_characters:
        print(f"\n{len(result.unmatched_characters)} unmatched character(s) flagged for review:")
        for uc in result.unmatched_characters:
            print(f"  - {uc.name_in_text}: {uc.note}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit(f"Usage: python {sys.argv[0]} <{'|'.join(BATCHES)}>")
    run_batch(sys.argv[1])
