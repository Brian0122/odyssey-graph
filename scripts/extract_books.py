"""
Step 6: Extract locations, events, and relationships from Odyssey text
(Samuel Butler translation) using Gemini.

One-off data-preparation script — not part of the live query agent, which
stays on the Gemini query agent per CLAUDE.md's LLM 供應商使用範圍 (the
extraction model is set separately below, per CLAUDE.md's stated split:
extraction uses gemini-3.1-flash-lite, the live query agent uses
gemini-3.6-flash).

Characters are referenced ONLY by the fixed `slug`s in
data/characters_canonical.json (upsert key shared with the Wikidata
pipeline). Locations and events are new in each pass, so they don't have
real MongoDB _ids yet: the model assigns temporary local ids (temp_id,
e.g. "loc_1", "event_1") and relationships reference those; a later
import step resolves temp_id -> real ObjectId before writing to MongoDB.

Runs one BATCH at a time (see BATCHES below), each with its own source
text / output file / order range / hand-curated location+event "floor"
list — NOT a single call across all books. Books 9-12's existing
data/extraction_gemini.json is the original, already-demo-verified batch
and is never regenerated by this script; new batches (Book 5, Books
21-24) get their own output files that scripts/import_to_mongodb.py
merges in alongside it, so expanding the dataset can't silently alter
data the flagship demo questions already depend on.

Usage: python scripts/extract_books.py <batch_name>
  batch_name one of: book5, books21-24
"""

import json
import os
import sys
from pathlib import Path
from typing import List, Literal, Optional

from dotenv import load_dotenv
from google import genai
from google.genai import types
from opencc import OpenCC
from pydantic import BaseModel

load_dotenv()

# Gemini is instructed to write Traditional Chinese, but LLMs don't reliably
# honor that distinction from Simplified — convert programmatically as a
# safety net rather than trusting the prompt alone. s2twp = Simplified ->
# Traditional with Taiwan-standard phrasing (not just character shapes).
_CC = OpenCC("s2twp")


def _to_traditional(obj):
    """Recursively convert every 'zh' string field in a nested dict/list to
    Traditional Chinese (Taiwan phrasing) via OpenCC."""
    if isinstance(obj, dict):
        return {
            k: (_CC.convert(v) if k == "zh" and isinstance(v, str) else _to_traditional(v))
            for k, v in obj.items()
        }
    if isinstance(obj, list):
        return [_to_traditional(item) for item in obj]
    return obj


DATA_DIR = Path(__file__).resolve().parent.parent / "data"
CANONICAL_PATH = DATA_DIR / "characters_canonical.json"

MODEL = "gemini-3.1-flash-lite"


class Bilingual(BaseModel):
    en: str
    zh: str


class ExtractedLocation(BaseModel):
    temp_id: str
    name: Bilingual
    description: Bilingual
    order: int
    book_chapter: str


class ExtractedEvent(BaseModel):
    temp_id: str
    name: Bilingual
    description: Bilingual
    location_temp_id: str
    order: int
    book_chapter: str
    source_excerpt: str
    character_slugs: List[str]


class ExtractedRelationship(BaseModel):
    from_ref: str
    from_type: Literal["character", "location", "event"]
    to_ref: str
    to_type: Literal["character", "location", "event"]
    relation: str
    description: Optional[Bilingual] = None


class UnmatchedCharacter(BaseModel):
    name_in_text: str
    note: str


class ExtractionResult(BaseModel):
    locations: List[ExtractedLocation]
    events: List[ExtractedEvent]
    relationships: List[ExtractedRelationship]
    unmatched_characters: List[UnmatchedCharacter]


def build_prompt(canonical_chars: list, book_text: str, book_label: str,
                  location_floor: str, event_floor: str,
                  order_note: str, extra_notes: str = "") -> str:
    char_list_lines = []
    for c in canonical_chars:
        aliases = f" (also called: {', '.join(c['aliases'])})" if c.get("aliases") else ""
        char_list_lines.append(f"- slug: \"{c['slug']}\" — {c['name_en']}{aliases}, type: {c['type']}")
    char_list = "\n".join(char_list_lines)

    return f"""You are extracting structured data from Homer's Odyssey, {book_label}
(Samuel Butler's 1900 English prose translation), for a knowledge-graph demo.

## Canonical character list (CLOSED SET — do not invent characters)
Every character reference in your output MUST use one of these exact slugs.
The text may use alternate names (e.g. "Ulysses" = Odysseus, "Neptune" = Poseidon,
"Jove"/"Jupiter" = Zeus, "Teiresias" = Tiresias, "the sun-god" = Helios,
"Mercury" = Hermes, "Minerva" = Athena, "Euryclea" = Eurycleia) — map them
to the correct slug.

{char_list}

If you encounter a named, narratively significant character who is NOT in this
list, do NOT invent a slug for them or silently drop them — add them to
`unmatched_characters` instead, with the name as it appears in the text and a
short note on their role. Minor unnamed crew members/suitors ("his men", "the
suitors" collectively) should just be omitted entirely — don't create entries
for them; only named suitors already in the canonical list (antinous,
eurymachus) get individual events/relationships, the rest of the suitors as a
group don't need separate tracking.

## What to extract

1. **locations** — each distinct place/setting in this text.
{location_floor}
   Assign each a `temp_id` like "loc_1", "loc_2", ... {order_note}

2. **events** — significant plot events. Do not compress or skip.
{event_floor}
   Assign `temp_id` like "event_1", "event_2", ... `order` follows the same
   sequence as locations (events and locations share one timeline).
   `location_temp_id` must reference a location's `temp_id` from this same
   extraction. `source_excerpt` is a short (1-3 sentence) VERBATIM quote from
   the English text that supports this event — used later to show "why the AI
   said this" citations. `character_slugs` lists every character (by slug)
   involved in or present at the event — this is the ONLY place participation
   is recorded, do not also create a relationship edge for it (see below).

3. **relationships** — edges between characters, and between events. Keep this
   list focused on narrative causality and character dynamics — NOT
   participation (that's `character_slugs` on the event) and NOT family ties.

   **Absolutely do NOT extract family/genealogical relationships** — no
   `SON_OF`, `FATHER_OF`, `MOTHER_OF`, `CHILD_OF`, `SIBLING_OF`, `MARRIED_TO`,
   or anything equivalent, even if the text states it explicitly. That data
   already exists from a separate Wikidata pipeline — adding it here creates
   duplicate edges. If you're unsure whether a relation is "family" vs
   "narrative", leave it out.

   What TO extract:
   - character-to-character narrative dynamics: e.g. ("odysseus", "BLINDS",
     "polyphemus"), ("poseidon", "ANTAGONIST_OF", "odysseus"), ("odysseus",
     "KILLS", "antinous") — use short, specific verb-style relation labels
     consistent with this style (existing ones in the graph: BLINDS, CAUSES,
     ANTAGONIST_OF — reuse those where they fit, or add a new one like KILLS
     following the same style, rather than a generic label)
   - event-to-event causality where the text makes it explicit
   - event-to-character causality where an event directly produces a
     character-level consequence (e.g. an event "CAUSES" a god's enmity),
     IN ADDITION to the character-level edge above — both are useful for
     different graph queries
   Do NOT create LOCATED_AT edges for events — that's already captured by
   `location_temp_id` on the event. Do NOT create PARTICIPATES_IN edges —
   that's already captured by `character_slugs` on the event.

{extra_notes}

## Output language
`name`/`description` fields need both `en` (concise, based on the English
text) and `zh` (natural Traditional Chinese translation/summary, not a
literal word-for-word translation — write for a Chinese-reading audience who
hasn't necessarily read Homer). `source_excerpt` stays in English only (it's
a direct quote).

## Source text ({book_label}, Samuel Butler translation)

{book_text}
"""


